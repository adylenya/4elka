import Foundation

/// Источник, которого нет: адаптер не найден ни в ресурсах приложения, ни в
/// дереве сборки.
///
/// Заглушка нужна, чтобы плеер сказал «плеер недоступен» словами. Без неё
/// координатор оставался бы в положении «доступен, но пусто» — то есть панель
/// показывала бы «ничего не играет» при полностью отсутствующей подсистеме, и
/// отличить одно от другого было бы нечем. Молчаливая смерть плеера уже была
/// дефектом, и повторять её нельзя.
@MainActor
public final class MissingMediaSource: MediaSource {
    public init() {}

    public func start(onState: @escaping @MainActor (NowPlaying) -> Void,
                      onUnavailable: @escaping @MainActor () -> Void) {
        onUnavailable()
    }

    public func stop() {}

    /// Команды посылать некуда. Молча: жаловаться уже пожаловались один раз при
    /// запуске, а кнопки в этом положении и так не показываются.
    public func send(_ command: MediaCommand) {}
}
