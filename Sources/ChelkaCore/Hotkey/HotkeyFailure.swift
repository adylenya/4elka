import Carbon.HIToolbox
import Foundation

/// Почему сочетание не удалось зарегистрировать — причиной, а не одной
/// строкой в журнале.
///
/// Зачем причина. Раньше регистрация возвращала `false` в двух совершенно
/// разных случаях — сочетание занято чужим приложением и этот же экземпляр
/// уже зарегистрирован, — а печаталось на оба одно и то же: «занято другим
/// приложением». То есть сообщение могло врать, и человек искал виноватого
/// среди чужих приложений, когда виноват был вызывающий.
///
/// Тип из одних значений: `Sendable` достаётся бесплатно, показать его можно
/// откуда угодно.
public struct HotkeyFailure: Equatable, Sendable {
    public enum Reason: Equatable, Sendable {
        /// `eventHotKeyExistsErr`: сочетание уже за кем-то. Чаще всего это
        /// чужое приложение (Alfred, Raycast, свои настройки клавиатуры), но
        /// с той же ошибкой отвечает Carbon и на второго регистратора внутри
        /// нашего же процесса — поэтому текст осторожен в формулировке.
        case comboTaken
        /// Этот же экземпляр уже держит регистрацию. Сочетание при этом
        /// свободно, а виноват вызывающий: регистрировать второй раз нечего.
        case alreadyRegistered
        /// Прочие коды Carbon. Не сваливаем их в «занято»: причина неизвестна,
        /// и честнее показать код, чем назвать наугад.
        case systemRefused(OSStatus)
    }

    public let combo: HotkeyCombo
    public let reason: Reason

    public init(combo: HotkeyCombo, reason: Reason) {
        self.combo = combo
        self.reason = reason
    }

    /// Что показать человеку. Сочетание называется в каждом случае: у
    /// приложения нет ни иконки в доке, ни уведомлений, и текст рядом с
    /// выбором в настройках — единственное место, где об отказе можно узнать
    /// не открывая `Console.app`.
    public var message: String {
        switch reason {
        case .comboTaken:
            return "Сочетание \(combo.displayName) уже занято — скорее всего, другим " +
                   "приложением. Панель по нему не откроется: выберите другое."
        case .alreadyRegistered:
            return "Сочетание \(combo.displayName) уже зарегистрировано этим приложением — " +
                   "повторная регистрация ничего не даёт."
        case .systemRefused(let status):
            return "Система отказала в регистрации \(combo.displayName), код \(status). " +
                   "Панель по этому сочетанию не откроется."
        }
    }
}
