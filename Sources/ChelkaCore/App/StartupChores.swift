import Foundation

/// Уборка, которую приложение делает один раз на старте.
///
/// Вынесена из `ChelkaAppDelegate` не для красоты: внутри делегата её нечем
/// проверить, не поднимая само приложение, — а без проверки «уборка на старте»
/// именно так и потерялась. Временный каталог жеста подметался ТОЛЬКО в начале
/// следующего перетаскивания: человек один раз вытащил двадцать картинок,
/// закрыл приложение и неделю не перетаскивал — сотни мегабайт лежат, файлы
/// давно старше часа, и убирать их некому.
///
/// Параметры — со значениями по умолчанию: приложение зовёт `run()` без
/// аргументов, тест подставляет свой каталог и своё «сейчас».
public enum StartupChores {
    public static func run(dragTemp: URL = AppPaths.dragTemp, now: Date = Date()) {
        DragTempCleaner(root: dragTemp).sweep(now: now)
    }
}
