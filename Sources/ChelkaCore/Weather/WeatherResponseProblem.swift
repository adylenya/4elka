import Foundation

/// Почему ответ не стал погодой.
///
/// Отдельный тип, а не `nil`: исходы лечатся по-разному, и в логе они обязаны
/// читаться по-разному. Сценарий, из-за которого это написано: приложение за
/// офисным прокси, который на `api.open-meteo.com` отдаёт страницу-заглушку.
/// Погода не обновлялась никогда, в интерфейсе тихо висело «3 дн назад», а в
/// логе за трое суток не было ни строчки — искать причину было не по чему.
public enum WeatherResponseProblem: Error, Equatable, Sendable {
    /// Ответ не разбирается как ответ Open-Meteo. Чаще всего это не погодный
    /// сервер вовсе: заглушка прокси, страница входа в гостевую сеть, пустой
    /// ответ. Поэтому в сообщение идёт начало пришедшего — по нему это и видно.
    case notWeatherAnswer(bytes: Int, beginning: String)
    /// Числа пришли и разобрались, но такой погоды не бывает: это сбой ответа,
    /// а не погода. «Проверьте сеть» тут сбило бы с толку.
    case implausibleTemperature(celsius: Double, feelsLike: Double)

    /// Строка для лога. Человеческими словами, потому что читать её будет
    /// человек в Console, а не разбор.
    public var message: String {
        switch self {
        case .notWeatherAnswer(let bytes, let beginning):
            return "ответ погоды не разобран (\(bytes) байт), пришло: \(beginning)"
        case .implausibleTemperature(let celsius, let feelsLike):
            return "погода не бывает такой: \(celsius)° (ощущается \(feelsLike)°), "
                + "считаю ответ сбоем и оставляю прежние данные"
        }
    }
}
